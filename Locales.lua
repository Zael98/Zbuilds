-- Display names of the internal source and type keys stored in Data.lua and saved imports.
local SOURCE_KEYS = { ["Guías extra"] = "SOURCE_EXTRA", ["Mis enlaces"] = "SOURCE_MINE" }

function ns.SourceName(source)
    return SOURCE_KEYS[source] and L[SOURCE_KEYS[source]] or source
end

function ns.CategoryName(key)
    return L["CAT_" .. (key or "none")] or key
end
